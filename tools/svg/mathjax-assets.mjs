import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = fileURLToPath(new URL('.', import.meta.url));
const resources = resolve(directory, '../../renderer-core/src/main/resources');
const destination = resolve(resources, 'mathjax');
const browser = resolve(directory, 'node_modules/mathjax');
const font = resolve(directory, 'node_modules/@mathjax/mathjax-newcm-font');
const assets = [
    [browser, ''],
    [resolve(font, 'svg'), 'fonts/mathjax-newcm-font/svg'],
    [resolve(font, 'svg.js'), 'fonts/mathjax-newcm-font/svg.js'],
];

export async function copyMathJax(checking) {
    const packages = ['mathjax', '@mathjax/src', '@mathjax/mathjax-newcm-font'];
    const lock = JSON.parse(await readFile(resolve(directory, 'package-lock.json'), 'utf8'));
    const version = lock.packages['node_modules/mathjax'].version;
    const provenance = [
        '# Bundled MathJax assets',
        '',
        'Generated by `tools/svg/mathjax-assets.mjs` from the pinned npm packages:',
        '',
        ...packages.map((name) => {
            const entry = lock.packages[`node_modules/${name}`];
            if (entry.version !== version) {
                throw new Error('MathJax source, browser and font versions must match');
            }
            return `- ${name}@${entry.version}\n  Integrity: ${entry.integrity}`;
        }),
        '',
        'MathJax and these SVG font tables use the Apache-2.0 license; see LICENSE.',
        'The browser distribution is copied intact. SVG font chunks are added under fonts/.',
        '',
    ].join('\n');
    if (checking) {
        for (const [source, target] of assets) {
            await compare(source, resolve(destination, target));
        }
        if ((await readFile(resolve(destination, 'PROVENANCE.md'), 'utf8')) !== provenance) {
            throw new Error('Stale MathJax provenance');
        }
        if ((await readFile(resolve(destination, 'VERSION'), 'utf8')) !== `${version}\n`) {
            throw new Error('Stale MathJax version');
        }
        return;
    }
    // This fixed generated directory is the only tree this helper may replace.
    if (destination !== resolve(resources, 'mathjax')) {
        throw new Error('Unexpected MathJax asset destination');
    }
    await rm(destination, { recursive: true, force: true });
    await mkdir(destination, { recursive: true });
    for (const [source, target] of assets) {
        await cp(source, resolve(destination, target), { recursive: true });
    }
    await writeFile(resolve(destination, 'VERSION'), `${version}\n`);
    await writeFile(resolve(destination, 'PROVENANCE.md'), provenance);
}

async function compare(source, target) {
    const entries = await readdir(source, { withFileTypes: true }).catch(() => null);
    if (entries) {
        for (const entry of entries) {
            await compare(resolve(source, entry.name), resolve(target, entry.name));
        }
    } else if (!(await readFile(source)).equals(await readFile(target))) {
        throw new Error(`Stale MathJax asset: ${target}`);
    }
}
