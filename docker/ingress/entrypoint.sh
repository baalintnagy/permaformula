#!/bin/sh
set -eu
: "${PERMMATH_HOST:?API origin is required}"
: "${PERMMATH_IMAGE_HOST:?Image origin is required}"
PERMMATH_HOST=${PERMMATH_HOST%/}
PERMMATH_IMAGE_HOST=${PERMMATH_IMAGE_HOST%/}
export PERMMATH_HOST PERMMATH_IMAGE_HOST
# Native nginx controls; accept positive integers only, never directive fragments.
: "${PERMMATH_INGRESS_CLIENT_CONNECTIONS:=64}"
: "${PERMMATH_INGRESS_TOTAL_CONNECTIONS:=128}"
: "${PERMMATH_INGRESS_HEADER_TIMEOUT_SECONDS:=15}"
: "${PERMMATH_INGRESS_BODY_TIMEOUT_SECONDS:=30}"
: "${PERMMATH_INGRESS_SEND_TIMEOUT_SECONDS:=30}"
: "${PERMMATH_INGRESS_KEEPALIVE_TIMEOUT_SECONDS:=15}"
for value in "$PERMMATH_INGRESS_CLIENT_CONNECTIONS" "$PERMMATH_INGRESS_TOTAL_CONNECTIONS" \
    "$PERMMATH_INGRESS_HEADER_TIMEOUT_SECONDS" "$PERMMATH_INGRESS_BODY_TIMEOUT_SECONDS" \
    "$PERMMATH_INGRESS_SEND_TIMEOUT_SECONDS" "$PERMMATH_INGRESS_KEEPALIVE_TIMEOUT_SECONDS"; do
    case "$value" in ''|*[!0-9]*|0*) echo 'Ingress limits must be positive decimal integers without leading zeros' >&2; exit 1;; esac
done
export PERMMATH_INGRESS_CLIENT_CONNECTIONS PERMMATH_INGRESS_TOTAL_CONNECTIONS \
    PERMMATH_INGRESS_HEADER_TIMEOUT_SECONDS PERMMATH_INGRESS_BODY_TIMEOUT_SECONDS \
    PERMMATH_INGRESS_SEND_TIMEOUT_SECONDS PERMMATH_INGRESS_KEEPALIVE_TIMEOUT_SECONDS
# Expand only listed settings, preserving native nginx variables.
envsubst '${PERMMATH_HOST} ${PERMMATH_IMAGE_HOST} ${PERMMATH_INGRESS_CLIENT_CONNECTIONS} ${PERMMATH_INGRESS_TOTAL_CONNECTIONS} ${PERMMATH_INGRESS_HEADER_TIMEOUT_SECONDS} ${PERMMATH_INGRESS_BODY_TIMEOUT_SECONDS} ${PERMMATH_INGRESS_SEND_TIMEOUT_SECONDS} ${PERMMATH_INGRESS_KEEPALIVE_TIMEOUT_SECONDS}' < /etc/nginx/nginx.conf.template > /tmp/nginx.conf
exec nginx -c /tmp/nginx.conf -e stderr -g 'daemon off;'
