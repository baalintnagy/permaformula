package org.permmath;

import static org.springframework.http.MediaType.APPLICATION_JSON_VALUE;


import static org.springframework.http.MediaType.TEXT_PLAIN_VALUE;
import static org.springframework.http.ResponseEntity.ok;

import java.io.IOException;
import java.util.List;

import jakarta.validation.constraints.NotBlank;

import org.permmath.rendering.GeneratedImageService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import org.permmath.url.ImageDescriptor;
import org.permmath.url.UrlService;
import org.permmath.validation.ValidImageWidth;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.ResponseEntity;
import org.jspecify.annotations.Nullable;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;


@Validated
@RestController
public class PermMathController {

    @Autowired
    private UrlService urlService;

    @Autowired
    private GeneratedImageService generatedImageService;

    @Operation(summary = "Render a single ASCIIMath formula as SVG",
            description = "Pass an uncompressed plain ASCIIMath formula without HTML or backtick delimiters. Dimensions follow the formula; styling and layout options are not supported. "
                    + "Returns a standalone SVG with embedded glyph paths. No browser is launched.")
    @GetMapping(path = "/img", produces = "image/svg+xml")
    public ResponseEntity<String> getImg(
            @Parameter(description = "Plain ASCIIMath formula, URL-encoded as a query parameter", example = "sqrt(x^2 + y^2)")
            @NotBlank @RequestParam String formula) throws IOException {
        return ok().contentType(org.springframework.http.MediaType.parseMediaType("image/svg+xml;charset=UTF-8"))
                .body(generatedImageService.getImg(formula));
    }

    @Operation(summary = "Create a compressed image permalink",
            description = "Serializes the content and optional layout settings into a UTF-8 JSON descriptor, "
                    + "compresses it with GZIP and Base64, and returns an /image?ubcq=... permalink. "
                    + "No rendering is performed. For formula-only SVG, call /img directly with its formula parameter.")
    @GetMapping(path = "/url", produces = { TEXT_PLAIN_VALUE, APPLICATION_JSON_VALUE })
    public String getUrl(
            @Parameter(description = "HTML content with backtick-delimited ASCIIMath for /image",
                    example = "<p>`sqrt(x^2 + y^2)`</p>")
            @NotBlank @RequestParam String formula,
            @Parameter(description = "HTML layout width in CSS pixels, from 220 to 4000. Defaults to the configured width (800 by default).", example = "800")
            @Nullable @ValidImageWidth @RequestParam(required = false) Integer imageWidth,
            @Parameter(description = "External stylesheet URLs in application order. Repeat this parameter for multiple stylesheets. Used by /image.",
                    example = "[\"https://example.com/formula.css\"]")
            @Nullable @RequestParam(required = false) List<@NotBlank String> styleRefs,
            @Parameter(description = "Inline CSS stylesheet applied after external stylesheets. Used by /image.",
                    example = "body { margin: 0; color: darkblue; font-family: sans-serif; }")
            @Nullable @RequestParam(required = false) String style) throws IOException {
        return urlService.getImageUrl(formula, imageWidth, styleRefs, style);
    }


    @Operation(summary = "Render compressed styled HTML as SVG",
            description = "Decodes the payload generated by /url and renders its HTML, CSS and backtick-delimited ASCIIMath "
                    + "using Chromium. Returns SVG with styled HTML inside foreignObject "
                    + "and math glyphs as vector paths. Intended for browsers; use /img for standalone formula SVG.")
    @GetMapping(value = "/image", produces = "image/svg+xml")
    public ResponseEntity<String> getImage(
            @Parameter(description = "Compressed descriptor from the ubcq parameter of a /url permalink. Paste the decoded parameter value into Swagger; it handles URL encoding.")
            @NotBlank @RequestParam String ubcq) throws IOException {
        return ok()
                .contentType(org.springframework.http.MediaType.parseMediaType("image/svg+xml;charset=UTF-8"))
                .body(generatedImageService.getImage(
                        urlService.decodeUbcq(ubcq)));

    }

    @Operation(summary = "Decode a compressed image descriptor",
            description = "Base64-decodes and GZIP-decompresses ubcq, then returns the JSON descriptor without rendering. "
                    + "The response contains forumla (historical spelling), and any imageWidth, styleRefs and style options.")
    @GetMapping(path = "/decode", produces = { APPLICATION_JSON_VALUE })
    public ImageDescriptor getDecode(
            @Parameter(description = "Compressed descriptor from the ubcq parameter of a /url permalink. Supply the payload, not the full permalink.")
            @NotBlank @RequestParam String ubcq) throws IOException {
        return urlService.decodeUbcq(ubcq);
    }

}
